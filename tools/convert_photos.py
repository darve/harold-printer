#!/usr/bin/env python3
"""Convert the images in photos/ into a C source file for the firmware.

Each image is rotated per its EXIF data, scaled to the printer's 384 px width,
tone-adjusted for thermal paper, Floyd-Steinberg dithered to 1 bit, and packed
MSB first with 1 = black. The output defines `photos[]` and `photo_count`
(see src/photos.h).

The build runs this automatically. To preview the dithered results:
    python3 tools/convert_photos.py photos --preview preview/
"""

import argparse
import sys
from pathlib import Path

try:
    from PIL import Image, ImageEnhance, ImageFilter, ImageOps
except ImportError:
    sys.exit("convert_photos.py needs Pillow: pip3 install pillow")

WIDTH = 384
EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".gif", ".webp", ".tif", ".tiff"}
FLASH_WARN_BYTES = 3 * 1024 * 1024  # Pico 2 has 4 MB; leave room for code


def convert(path, max_height, gamma):
    img = Image.open(path)
    img = ImageOps.exif_transpose(img)
    img = img.convert("L")

    h = round(img.height * WIDTH / img.width)
    img = img.resize((WIDTH, h), Image.LANCZOS)
    if h > max_height:
        top = (h - max_height) // 2
        img = img.crop((0, top, WIDTH, top + max_height))

    # Thermal heads print dark and lose shadow detail, so stretch the levels,
    # lift the midtones, and sharpen a little before dithering.
    img = ImageOps.autocontrast(img, cutoff=1)
    img = img.point(lambda v: round(255 * (v / 255) ** (1 / gamma)))
    img = img.filter(ImageFilter.UnsharpMask(radius=1.5, percent=80, threshold=2))
    img = ImageEnhance.Contrast(img).enhance(1.1)

    return img.convert("1", dither=Image.Dither.FLOYDSTEINBERG)


def pack(img):
    # In mode "1", 0 is black. The printer wants 1 = black, MSB first.
    w, h = img.size
    px = img.load()
    out = bytearray()
    for y in range(h):
        for xb in range(0, w, 8):
            byte = 0
            for bit in range(8):
                x = xb + bit
                if x < w and px[x, y] == 0:
                    byte |= 0x80 >> bit
            out.append(byte)
    return bytes(out)


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("photo_dir", type=Path)
    ap.add_argument("--out", type=Path, help="C file to write")
    ap.add_argument("--preview", type=Path, help="also save dithered PNGs here")
    ap.add_argument("--max-height", type=int, default=768, help="crop taller images to this many px (default 768)")
    ap.add_argument("--gamma", type=float, default=1.4, help="midtone lift, >1 is lighter (default 1.4)")
    args = ap.parse_args()

    files = sorted(p for p in args.photo_dir.iterdir()
                   if p.is_file() and p.suffix.lower() in EXTENSIONS) if args.photo_dir.is_dir() else []

    entries = []
    total = 0
    for i, path in enumerate(files):
        try:
            img = convert(path, args.max_height, args.gamma)
        except Exception as e:  # noqa: BLE001 - skip unreadable files, keep building
            print(f"convert_photos: skipping {path.name}: {e}", file=sys.stderr)
            continue
        data = pack(img)
        total += len(data)
        entries.append((f"photo_{i}", path.name, img.size[1], data))
        if args.preview:
            args.preview.mkdir(parents=True, exist_ok=True)
            img.save(args.preview / (path.stem + ".png"))

    print(f"convert_photos: {len(entries)} photo(s), {total // 1024} KB", file=sys.stderr)
    if total > FLASH_WARN_BYTES:
        print(f"convert_photos: WARNING: {total // 1024} KB of photos may not fit in flash", file=sys.stderr)

    if not args.out:
        return

    lines = ["// Generated by tools/convert_photos.py. Do not edit.", "", '#include "photos.h"', ""]
    for sym, _, _, data in entries:
        lines.append(f"static const uint8_t {sym}[{len(data)}] = {{")
        for off in range(0, len(data), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in data[off:off + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("const photo_t photos[] = {")
    for sym, name, h, _ in entries:
        lines.append(f"  {{{c_string(name)}, {WIDTH}, {h}, {sym}}},")
    if not entries:
        lines.append("  {0},  // placeholder; photo_count is 0")
    lines.append("};")
    lines.append(f"const unsigned photo_count = {len(entries)};")
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
